#include "beep.h"

/*******************************************************************************
* 函数功能 : 蜂鸣器报警函数（有源/无源均可）
* 输入     : time：报警持续时间（周期数，每个周期包含高低电平各一次）
*            fre：频率控制（延时10us的倍数，每个半周期延时fre*10us）
*******************************************************************************/
void beep_alarm(u16 time, u16 fre)
{
    while(time--)          // 重复 time 个完整周期
    {
        BEEP = !BEEP;      // 翻转电平（输出方波）
        delay_10us(fre);   // 保持该电平 fre*10us
    }
}